def main() -> int:
    o = json.loads(OUTPUTS.read_text())
    f = figures(o)
    safe = {k: html.escape(v) for k, v in f.items()}
    SITE.parent.mkdir(parents=True, exist_ok=True)
    SITE.write_text(PAGE.format(owner=FINAL_OWNER, repo=REPO, dashboard=DASHBOARD_URL, **safe))
    (SITE.parent / ".nojekyll").write_text("")
    readme = README.read_text()
    block = README_BLOCK.format(**f)
    readme = re.sub(r"<!-- outputs:start.*?<!-- outputs:end -->", lambda _: block, readme, flags=re.S)
    README.write_text(readme)
    print(f"wrote {SITE.relative_to(ROOT)} and refreshed README key numbers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
