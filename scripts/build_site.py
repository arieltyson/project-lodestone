def figures(o: dict) -> dict[str, str]:
    n = o["names"]
    pct = lambda v: f"{'+' if v >= 0 else '−'}{abs(v) * 100:.0f}%"
    usd = lambda v: f"US${v / 1000:.1f}Bn" if abs(v) >= 1000 else f"US${v:,.0f}M"
    return {
        "offer": f"C${n['DEAL_OFFER_CAD']:.2f}",
        "premium": f"{n['DEAL_PREMIUM']:.0%}",
        "cash_pct": f"{n['DEAL_CASH_PCT']:.0%}",
        "stock_pct": f"{1 - n['DEAL_CASH_PCT']:.0%}",
        "equity": usd(n["DEAL_EQUITY_USD"]),
        "ev": usd(n["DEAL_EV_USD"]),
        "ev_ebitda": f"{n['DEAL_EV_EBITDA']:.1f}x",
        "eps27": pct(n["ACC_EPS_2027"]),
        "eps28": pct(n["ACC_EPS_2028"]),
        "cfps27": pct(n["ACC_CFPS_2027"]),
        "cfps28": pct(n["ACC_CFPS_2028"]),
        "navps": pct(n["ACC_NAVPS"]),
        "synergies": f"US${n['SYN_RUNRATE']:,.0f}M",
        "syn_npv": usd(n["SYN_NPV"]),
        "own_cg": f"{n['PF_OWN_CG']:.0%}",
        "leverage": f"{n['PF_LEVERAGE']:.1f}x",
        "cg_pnav": f"{n['CG_PNAV']:.2f}x",
        "ero_pnav": f"{n['ERO_PNAV']:.2f}x",
        "snapshot": f"{o['timestamp_utc'][:4]}-{o['timestamp_utc'][4:6]}-{o['timestamp_utc'][6:8]}",
        "cu_spot": f"US${o['spot']['copper']:.2f}/lb",
        "cu_lt": f"US${o['deck']['copper'][-1]:.2f}/lb",
        "au_lt": f"US${o['deck']['gold'][-1]:,.0f}/oz",
    }


